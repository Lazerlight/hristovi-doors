function openCatalog(categoryId) {
  try {
    const data = productCatalog[categoryId];
    if (!data) return;

    const modal = document.getElementById('catalogModal');
    const title = document.getElementById('catalogTitle');
    const subtitle = document.getElementById('catalogSubtitle');
    const list = document.getElementById('catalogList');
    if (!modal || !title || !subtitle || !list) return;

    title.textContent = data.title;
    subtitle.textContent = data.subtitle;

    const fragment = document.createDocumentFragment();
    data.items.forEach((item) => {
      const article = document.createElement('article');
      article.className = 'catalog-item';

      const imageWrap = document.createElement('div');
      imageWrap.className = 'catalog-item__image';
      const img = document.createElement('img');
      img.src = item.img;
      img.alt = item.name;
      img.loading = 'lazy';
      img.decoding = 'async';
      img.width = 96;
      img.height = 72;
      imageWrap.appendChild(img);

      const body = document.createElement('div');
      body.className = 'catalog-item__body';
      const name = document.createElement('h3');
      name.className = 'catalog-item__name';
      name.textContent = item.name;
      const meta = document.createElement('p');
      meta.className = 'catalog-item__meta';
      meta.textContent = item.meta;
      body.appendChild(name);
      body.appendChild(meta);

      article.appendChild(imageWrap);
      article.appendChild(body);
      fragment.appendChild(article);
    });

    list.replaceChildren(fragment);

    requestAnimationFrame(() => {
      modal.classList.add('catalog-modal--open');
      document.body.classList.add('catalog-open');
      modal.setAttribute('aria-hidden', 'false');
      const closeBtn = document.getElementById('catalogClose');
      if (closeBtn) closeBtn.focus();
    });
  } catch (err) {
    console.error('Catalog open failed:', err);
  }
}

function closeCatalog() {
  const modal = document.getElementById('catalogModal');
  if (!modal) return;
  modal.classList.remove('catalog-modal--open');
  document.body.classList.remove('catalog-open');
  modal.setAttribute('aria-hidden', 'true');
}

function initCatalog() {
  document.querySelectorAll('[data-catalog]').forEach((el) => {
    el.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      openCatalog(el.getAttribute('data-catalog'));
    });
    el.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        openCatalog(el.getAttribute('data-catalog'));
      }
    });
  });

  const closeBtn = document.getElementById('catalogClose');
  const backdrop = document.getElementById('catalogBackdrop');
  if (closeBtn) closeBtn.addEventListener('click', closeCatalog);
  if (backdrop) backdrop.addEventListener('click', closeCatalog);

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeCatalog();
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initCatalog);
} else {
  initCatalog();
}
